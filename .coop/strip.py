# -*- coding: utf-8 -*-
"""DAO COOPTECH build of Odoo: remove modules that call Odoo S.A. services.

Seeds: modules whose code has an Odoo S.A. service endpoint or imports a
service module (see coop_services.py), plus owner decisions (EXTRA_SEEDS).
Removed: seeds and every module that depends on them, recomputed from the
manifests on every sync, so a new upstream module depending on a service
goes too.

    python .coop/strip.py          # print the list
    python .coop/strip.py --apply  # git rm the directories, write the list

Run on a clean tree right after rebasing on upstream; commit the result as
the top commit "Strip Odoo S.A. service modules".
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import coop_services as cs  # noqa: E402

LIST = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'removed-modules.txt')


def main(apply):
    mods = cs.manifests()
    roots = cs.seeds(mods)
    removed = cs.closure(mods, roots)
    lines = ['# Generated by .coop/strip.py. Seeds are marked with *.']
    lines += ['%s%s' % (name, ' *' if name in roots else '') for name in sorted(removed)]
    print('modules %d, seeds %d, removed %d' % (len(mods), len(roots), len(removed)))
    if not apply:
        print('\n'.join(lines[1:]))
        return 0
    paths = [os.path.relpath(mods[name][0], cs.ROOT) for name in sorted(removed)]
    for i in range(0, len(paths), 50):
        subprocess.check_call(['git', 'rm', '-r', '-q', '--'] + paths[i:i + 50], cwd=cs.ROOT)
    with open(LIST, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    subprocess.check_call(['git', 'add', '--', os.path.relpath(LIST, cs.ROOT)], cwd=cs.ROOT)
    return 0


if __name__ == '__main__':
    sys.exit(main('--apply' in sys.argv))
